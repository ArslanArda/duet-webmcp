export const dictionaries = { en, tr } as const;

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>) {
  let text: string = dictionaries[locale][key] ?? en[key];
  if (vars)
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  return text;
}

export function formatRelativeTime(timestamp: number, locale: Locale, now = Date.now()) {
  const seconds = Math.max(0, Math.round((now - timestamp) / 1000));
  if (seconds < 60) return t(locale, "justNow");
  if (seconds < 3600) return t(locale, "minutesAgo", { count: Math.floor(seconds / 60) });
  if (seconds < 86400) return t(locale, "hoursAgo", { count: Math.floor(seconds / 3600) });
  return new Date(timestamp).toLocaleDateString(locale === "tr" ? "tr-TR" : "en-US");
}
